/* Arrow Escape - core puzzle logic + deterministic level generator.
   Dependency-free. Runs in the browser and in Node (used by the validator).

   Rule: an arrow occupies a cell and points N / E / S / W. Tapping it removes it
   ONLY if every cell from it to the board edge, in its direction, is empty of
   other arrows. The goal is to clear the board.

   Every level is generated by reverse placement: arrows are placed one at a time
   onto an empty board, each new arrow required to have a clear lane with respect
   to everything already placed. The reverse of the placement order is therefore
   a valid clearing order, so every level is solvable by construction. */
(function (root) {
  "use strict";

  var DIRS = [[-1, 0], [0, 1], [1, 0], [0, -1]]; // 0=N 1=E 2=S 3=W

  function key(r, c) { return r + "," + c; }
  function inBounds(R, C, r, c) { return r >= 0 && r < R && c >= 0 && c < C; }

  function occSet(arrows) {
    var s = new Set();
    for (var i = 0; i < arrows.length; i++) s.add(key(arrows[i][0], arrows[i][1]));
    return s;
  }

  // Is the lane from (r,c) to the edge, in direction d, free of every arrow in occ?
  function rayClear(R, C, r, c, d, occ) {
    var dr = DIRS[d][0], dc = DIRS[d][1];
    var rr = r + dr, cc = c + dc;
    while (inBounds(R, C, rr, cc)) {
      if (occ.has(key(rr, cc))) return false;
      rr += dr; cc += dc;
    }
    return true;
  }

  function canRemove(R, C, arrows, i) {
    var occ = occSet(arrows);
    return rayClear(R, C, arrows[i][0], arrows[i][1], arrows[i][2], occ);
  }

  function firstRemovable(R, C, arrows) {
    for (var i = 0; i < arrows.length; i++) if (canRemove(R, C, arrows, i)) return i;
    return -1;
  }

  function removeAt(arrows, i) {
    var ns = arrows.slice();
    ns.splice(i, 1);
    return ns;
  }

  // Greedy clear. Removing an arrow can never create a new blockage, so if a
  // level is solvable at all greedy always finishes -> this check is complete.
  function solve(R, C, arrows) {
    var st = arrows.slice(), path = [];
    while (st.length) {
      var i = firstRemovable(R, C, st);
      if (i < 0) return null;
      path.push([st[i][0], st[i][1]]);
      st = removeAt(st, i);
    }
    return path;
  }

  function isSolvable(R, C, arrows) { return solve(R, C, arrows) !== null; }

  function blockedCount(R, C, arrows) {
    var occ = occSet(arrows), n = 0;
    for (var i = 0; i < arrows.length; i++)
      if (!rayClear(R, C, arrows[i][0], arrows[i][1], arrows[i][2], occ)) n++;
    return n;
  }

  // ---- deterministic PRNG (mulberry32) + id hashing ----
  function mulberry32(a) {
    return function () {
      a |= 0; a = a + 0x6D2B79F5 | 0;
      var t = Math.imul(a ^ a >>> 15, 1 | a);
      t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
      return ((t ^ t >>> 14) >>> 0) / 4294967296;
    };
  }
  function hashId(id) {
    var h = (2166136261 ^ Math.imul((id + 0x9E3779B9) | 0, 2654435761)) >>> 0;
    h = Math.imul(h ^ (h >>> 15), 2246822519);
    h = Math.imul(h ^ (h >>> 13), 3266489917);
    return (h ^ (h >>> 16)) >>> 0;
  }

  var SIZES = [[3, 3], [4, 4], [4, 5], [5, 5], [5, 6], [6, 6], [6, 7], [7, 7], [8, 8], [8, 9], [9, 9]];
  var HARD_EVERY = 6;

  function params(id) {
    var ch = Math.min(Math.floor((id - 1) / 50), 239);
    var hard = (id % HARD_EVERY === 0);
    var s = SIZES[Math.min(ch, SIZES.length - 1)];
    var R = s[0], C = s[1];
    if (hard) { R = Math.min(9, R + 1); C = Math.min(9, C + 1); }
    var area = R * C;
    var frac = Math.min(0.58, 0.30 + 0.006 * ch) + (hard ? 0.08 : 0);
    var n = Math.max(3, Math.min(area - 1, Math.round(area * frac)));
    return { R: R, C: C, n: n, hard: hard };
  }

  function place(rng, R, C, n) {
    var occ = new Set(), placed = [];
    for (var k = 0; k < n; k++) {
      var done = false;
      for (var t = 0; t < 600; t++) {
        var r = Math.floor(rng() * R), c = Math.floor(rng() * C);
        if (occ.has(key(r, c))) continue;
        var d = Math.floor(rng() * 4);
        if (!rayClear(R, C, r, c, d, occ)) continue;
        placed.push([r, c, d]); occ.add(key(r, c)); done = true; break;
      }
      if (!done) break;
    }
    return placed;
  }

  function generate(id) {
    var p = params(id), rng = mulberry32(hashId(id)), best = null;
    for (var a = 0; a < 14; a++) {
      var placed = place(rng, p.R, p.C, p.n);
      if (placed.length < 3) continue;
      var blocked = blockedCount(p.R, p.C, placed);
      var cand = { id: id, rows: p.R, cols: p.C, arrows: placed, par: placed.length, blocked: blocked, hard: p.hard };
      if (id > 5 && blocked < 1) { if (!best) best = cand; continue; }
      return cand;
    }
    var pl = place(rng, p.R, p.C, p.n);
    return best || { id: id, rows: p.R, cols: p.C, arrows: pl, par: pl.length, blocked: 0, hard: p.hard };
  }

  root.APCore = {
    DIRS: DIRS, inBounds: inBounds, rayClear: rayClear, canRemove: canRemove,
    firstRemovable: firstRemovable, removeAt: removeAt, solve: solve,
    isSolvable: isSolvable, blockedCount: blockedCount,
    generate: generate, params: params, mulberry32: mulberry32, hashId: hashId
  };
  if (typeof module !== "undefined" && module.exports) module.exports = root.APCore;
})(typeof window !== "undefined" ? window : globalThis);
